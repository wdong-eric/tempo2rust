lines = (ROOT/'tempo2/readParfile.C').read_text().splitlines(True)

def predicate(s):
    s = s.strip()
    if s.startswith('if'): s=s[2:].strip()
    s = re.sub(r'strncasecmp\(\s*str\s*,\s*"([^"]*)"\s*,\s*(\d+)\s*\)\s*==\s*0',r'prefix(key, b"\1", \2)',s)
    s = re.sub(r'strcasecmp\(\s*str\s*,\s*"([^"]*)"\s*\)\s*(!=|==)\s*0',lambda m:('!' if m[2]=='!=' else '')+'key.eq_ignore_ascii_case(b"'+m[1]+'")',s)
    s = re.sub(r'strcmp\(\s*str\s*,\s*"([^"]*)"\s*\)\s*(!=|==)\s*0',lambda m:'(key '+m[2]+' b"'+m[1]+'")',s)
    s = re.sub(r'strstr\(\s*str\s*,\s*"([^"]*)"\s*\)\s*(!=|==)\s*NULL',lambda m:('!' if m[2]=='==' else '')+'contains(key, b"'+m[1]+'")',s)
    s = re.sub(r"isdigit\(str\[(\d+)\]\)",r'byte(key, \1).is_ascii_digit()',s)
    s = re.sub(r'str\[(\d+)\]',r'byte(key, \1)',s)
    s = re.sub(r"'([^']*)'",r"b'\1'",s)
    return s

def body(d):
    text=''.join(lines[d['line']-1:d['end_line']-1])
    text=re.sub(r'/\*.*?\*/|//[^\n]*','',text,flags=re.S)
    off=text.index('if')+2
    start=text.index('(',off); depth=1; end=start+1
    while depth:
        if text[end]=='(':depth+=1
        elif text[end]==')':depth-=1
        end+=1
    body=text[end:].strip()
    if body.startswith('{'):
        closed=body.count('{')==body.count('}')
        body=body[1:]
        if closed:body=body[:-1]
    return body.strip()

