    m=re.fullmatch(r'fscanf\(\s*fin\s*,\s*"([^"]+)"\s*,\s*(.*?)\s*\);',b,flags=re.S)
    if m:
        types=re.findall(r'%(?:lf|lg|d|f|s)',m[1]); fields=re.findall(r'psr->(\w+)(?!\[)',m[2])
