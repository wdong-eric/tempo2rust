#!/usr/bin/env python3
"""Replay accepted K actions without rebuilding or changing its evidence."""
import argparse, hashlib, json, os, re, subprocess
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parent.parent
K=ROOT/'validation/parameters'
BUILD=HERE/'build/parameters'

def generate_controls():
    profile=json.loads((K/'profile.json').read_text())
    fields=re.findall(r'FIELD\((\w+)\)',profile['generated']['controls.h']['text'])
    fields += ['clock','ephemeris','JPL_EPHEMERIS','rajStrPre','rajStrPost','decjStrPre','decjStrPost','ne_sw_ifuncN','nchromx','clockFromOverride','waveScale','setTelVelX','setTelVelY','setTelVelZ']
    target=ROOT/'rust/src/source_parameter_controls.rs'
    source='// Generated by validation/input_to_bat/check_parameters.py --generate.\n'
    source+='fn controls(p: &SourcePulsar, s: &mut Map, root: &str) {\n'
    source+=''.join(f'    s.insert(format!("{{root}}{f}"), p.{f}.wire());\n' for f in fields)
    target.write_text(source+'}\n')

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--release',action='store_true');ap.add_argument('--case',action='append');ap.add_argument('--generate',action='store_true');a=ap.parse_args()
    if a.generate:generate_controls();return
    BUILD.mkdir(exist_ok=True,parents=True)
    (BUILD/'runtime').mkdir(exist_ok=True)
    reference=K/'observations.json';cases=json.loads(reference.read_text())
    registry=next(e['result'] for e in cases[0]['events'] if e['op']=='registry' and e['phase']=='end')
    (BUILD/'registry.json').write_text(json.dumps(registry)+'\n')
    selected=[];dispositions=[]
    for case in cases:
        if a.case and case['id'] not in a.case:continue
        if case['id'] in ['defaults_missing','full_missing_env']:
            dispositions.append({'case':case['id'],'disposition':'native TEMPO2 environment missing; Rust source API requires an explicit runtime path and has no ambient-environment lookup'})
            continue
        for name,data in case['files'].items():
            p=BUILD/case['id']/name;p.parent.mkdir(exist_ok=True,parents=True)
            # K records byte strings as hex, with paths normalized in their content.
            p.write_text(data) if isinstance(data,str) else p.write_bytes(bytes(data))
        selected.append(case)
    text=json.dumps(selected).replace('{build}',str(BUILD)).replace('{case}',str(BUILD/'{case}'))
    # Resolve case-local paths separately, preserving runtime provenance.
    selected=json.loads(text)
    for case in selected:
        case_text=json.dumps(case).replace('{case}',case['id'])
        case.update(json.loads(case_text))
        for channel in ['stdout', 'stderr']:
            case[channel] = re.sub(re.escape(str(BUILD / 'cases')) + '/' + re.escape(case['id']) + r'-[0-9a-f]{10}(?=/)', str(BUILD / case['id']), case.get(channel, ''))
    (BUILD/'cases.json').write_text(json.dumps(selected)+'\n')
    env={**os.environ,'CARGO_HOME':str(ROOT/'rust/.cargo-home'),'GMP_MPFR_SYS_CACHE':str(ROOT/'rust/target/gmp-cache'),'AC_PARAMETER_CASES':str(BUILD)}
    cmd=['cargo','test','--manifest-path',str(ROOT/'rust/Cargo.toml'),'--locked','--offline',*(['--release'] if a.release else []),'--lib','source_par::parameter_corpus::k_corpus','--','--ignored','--exact','--nocapture','--test-threads=1']
    receipt=BUILD/('receipt-'+('release' if a.release else 'debug')+'.json');receipt.unlink(missing_ok=True)
    run=subprocess.run(cmd,env=env)
    receipt.write_text(json.dumps({'reference_sha256':hashlib.sha256(reference.read_bytes()).hexdigest(),'cases':len(selected),'dispositions':dispositions,'returncode':run.returncode},indent=2)+'\n')
    raise SystemExit(run.returncode)
if __name__=='__main__':main()
