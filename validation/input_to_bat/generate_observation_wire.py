#!/usr/bin/env python3
"""Test-only complete observation projection using accepted R membership and N ABI."""
import hashlib,json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];BUILD=ROOT/'validation/input_to_bat/build/observation_wire';BUILD.mkdir(parents=True,exist_ok=True)
fields=json.loads((ROOT/'validation/observation_storage_port/fields.json').read_text())['fields']
profile=json.loads((ROOT/'validation/tim_io/profile.json').read_text())
inc=next(a for a in profile['command'] if a.startswith('-I'))
assert hashlib.sha256((Path(inc[2:])/'tempo2.h').read_bytes()).hexdigest()==profile['stable']['header_dependencies']['{source}/tempo2.h']
source='#include "tempo2.h"\n#include <cstdio>\n#include <cstddef>\nint main(){\n'
for f in fields:source+=f'printf("{f["name"]} %zu %zu\\n",offsetof(observation,{f["name"]}),sizeof(((observation*)0)->{f["name"]}));\n'
source+='printf("RECORD %zu\\n",sizeof(observation));\n}\n'
cpp=BUILD/'layout.cc';cpp.write_text(source);exe=BUILD/'layout';cmd=[profile['command'][0],'-O2','-std=gnu++11','-DHAVE_CONFIG_H',inc,str(cpp),'-o',str(exe)];subprocess.run(cmd,check=True)
raw=subprocess.check_output([str(exe)]).decode();lines=raw.splitlines();size=int(lines.pop().split()[1]);assert size==7680
layout=[line.split() for line in lines];assert [f['name'] for f in fields]==[x[0] for x in layout]
out='// Generated by validation/input_to_bat/generate_observation_wire.py.\n'
out+='pub(crate) fn observation_bytes(o:&mut crate::observation::SourceObservation, b:&mut [u8],load:bool){\nassert_eq!(b.len(),7680);\n'
for name,off,n in layout:out+=f'span(&mut o.{name},&mut b[{off}..{int(off)+int(n)}],load);\n'
out+='}\n'
(ROOT/'rust/src/observation_corpus_fields.rs').write_text(out)
(BUILD/'receipt.json').write_text(json.dumps({'command':cmd,'layout':raw,'source_sha256':hashlib.sha256(cpp.read_bytes()).hexdigest(),'executable_sha256':hashlib.sha256(exe.read_bytes()).hexdigest(),'native_header_sha256':hashlib.sha256((Path(inc[2:])/'tempo2.h').read_bytes()).hexdigest()},indent=2)+'\n')
