#!/usr/bin/env python3
"""Emit Q's complete fixed-field projection from its frozen membership."""
import gzip,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
state=json.loads(gzip.decompress((ROOT/'validation/par_specialized/initial_state.json.gz').read_bytes()))
fields={}
for key in state:
    if not key.startswith('p0.') or key.startswith('p0.param['):continue
    field=key[3:];name=field.split('[')[0];fields[name]='[' in field
out=['// Generated by validation/input_to_bat/generate_par_fields.py from frozen Q membership.\n','fn fixed_fields(p:&mut SourcePulsar,root:&str,state:&mut Map,load:bool){\n']
for name,array in sorted(fields.items()):
    if array:out.append(f'for(i,x)in p.{name}.iter_mut().enumerate(){{field(x,&format!("{{root}}{name}[{{i}}]"),state,load);}}\n')
    else:out.append(f'field(&mut p.{name},&format!("{{root}}{name}"),state,load);\n')
out.append('}\n')
source=(ROOT/'rust/src/pulsar.rs').read_text()
for typ in ['Constraint','SeriesType']:
    body=re.search(r'pub enum '+typ+r' \{(.*?)\n\}',source,re.S)[1]
    values=re.findall(r'^\s*(\w+)\s*=\s*(\d+),',body,re.M)
    assert values
    out.append('impl Wire for '+typ+'{fn take(b:&mut &[u8])->Self{match i32::take(b){'+''.join(f'{n}=>Self::{v},' for v,n in values)+'_=>panic!("fixture enum"),}}fn put(&self,b:&mut Vec<u8>){(*self as i32).put(b);}}\n')
(ROOT/'rust/src/source_par_corpus_fields.rs').write_text(''.join(out))
print('Generated',len(fields),'Q fixed fields')
