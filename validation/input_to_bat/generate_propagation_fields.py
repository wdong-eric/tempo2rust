#!/usr/bin/env python3
"""Generate the complete AB typed projection from its frozen source map."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
types = json.loads((ROOT / 'validation/propagation/outputs/frozen/source_map.json').read_text())['types']
rust = {'pulsar': 'SourcePulsar', 'observation': 'SourceObservation',
        'clock_correction': 'crate::observation::SourceClockCorrection',
        'FitInfo': 'crate::pulsar::FitInfo', 'FitOutput': 'crate::pulsar::FitOutput',
        'storePrecision': 'crate::pulsar::StorePrecision'}
widths = {'double': 8, 'longdouble': 16, 'float': 4, 'int': 4, 'unsigned': 4,
          'char': 1, 'param_label': 4, 'constraint_label': 4,
          'enum constraint': 4, 'enum series_type': 4, 'uint64_t': 8, 'long long': 8}
out = ['// Generated by generate_propagation_fields.py; every frozen AB field.\n']
for kind, typ in rust.items():
    out.append(f'fn ab_{kind}(p:&mut {typ},root:&str,s:&mut Map,load:bool){{\n')
    for f in types[kind]:
        n, t, ext = f['name'], f['type'], f['extents']
        if kind == 'pulsar' and n in ('obsn', 'param'):
            continue  # Canonical owner/parameter projection in state().
        key = f'&format!("{{root}}.{n}")'
        if f['pointers'] or t.endswith('Func'):
            fn = 'null_array' if ext else 'null_pointer'
            out.append(f'{fn}(&mut p.{n},{key},s,load);\n')
        elif t in rust:
            if ext:
                assert len(ext) == 1
                out.append(f'for(i,x)in p.{n}.iter_mut().enumerate(){{ab_{t}(x,&format!("{{root}}.{n}[{{i}}]"),s,load);}}\n')
            else:
                out.append(f'ab_{t}(&mut p.{n},{key},s,load);\n')
        else:
            w = widths[t]
            floating = str(t in ('float', 'double', 'longdouble')).lower()
            out.append(f'ab_field(&mut p.{n},{key},{w},{floating},s,load);\n')
    out.append('}\n')
for kind in ('pulsar', 'observation'):
    out.append(f'fn set_{kind}(p:&mut {rust[kind]},name:&str,index:usize,value:&str){{match name{{\n')
    for f in types[kind]:
        n, t, ext = f['name'], f['type'], f['extents']
        if f['pointers'] or t not in widths or len(ext) > 1:
            continue
        if t == 'longdouble':
            cell = f'p.{n}[index]' if ext else f'p.{n}'
            out.append(f'"{n}"=>{{{cell}=Some(extended(value.as_bytes()).unwrap());}},\n')
            continue
        out.append(f'"{n}"=>set_cell(&mut p.{n},{widths[t]},"{t}",{str(bool(ext)).lower()},index,value),\n')
    out.append('_=>panic!("unknown AB caller field {name}"),}}\n')
(ROOT / 'rust/src/propagation_corpus_fields.rs').write_text(''.join(out))
print('Generated all 349 pulsar and 95 observation fields with recursive nested types.')
